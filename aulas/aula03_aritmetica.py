# --- AULA 03: OPERADORES ARITMÉTICOS ---

# Divisão Padrão (Sempre retorna Float)
div = 5 / 2 
print(f"Divisão comum (5 / 2): {div} | Tipo: {type(div)}")

# Divisão Inteira (Ignora a parte decimal)
div2 = 5 // 2 
print(f"Divisão inteira (5 // 2): {div2} | Tipo: {type(div2)}")

# Resto da Divisão (Módulo - Útil para par ou ímpar)
resto = 5 % 2
print(f"Resto da divisão (5 % 2): {resto} | Tipo: {type(resto)}")

# Exponenciação (Potência)
expo = 5 ** 2 
print(f"Exponenciação (5 ** 2): {expo} | Tipo: {type(expo)}")
